def _normalize(text: str) -> str:
    text = (text or "").lower().replace("ё", "е")
    text = re.sub(r"[^a-zа-я0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def _has_any(text: str, patterns: Iterable[str]) -> bool:
    return any(_normalize(pattern) in text for pattern in patterns)


def _add(profile: dict[str, list[str]], field: str, values: Iterable[str]):
    bucket = profile.setdefault(field, [])
    seen = set(bucket)
    for value in values:
        value = _normalize(value)
        if len(value) >= 3 and value not in seen:
            bucket.append(value)
            seen.add(value)


