def build_ai_profile(content_type: str, item: dict) -> dict[str, list[str]]:
    text = " ".join(
        [
            content_type,
            item.get("title", ""),
            item.get("desc", ""),
            " ".join(item.get("tags", []) or []),
            " ".join(item.get("ai_tags", []) or []),
            " ".join(item.get("premium_collections", []) or []),
            " ".join(item.get("platforms", []) or []),
        ]
    )
    normalized = _normalize(text)
    profile: dict[str, list[str]] = {}

    for field, patterns, values in PROFILE_RULES:
        if _has_any(normalized, patterns):
            _add(profile, field, values)

    for patterns, values in BEST_FOR_RULES:
        if _has_any(normalized, patterns):
            _add(profile, "best_for", values)

    for patterns, values in AVOID_RULES:
        if _has_any(normalized, patterns):
            _add(profile, "avoid_if", values)

    if item.get("premium_collections"):
        _add(profile, "format", ["премиум подборка"])
    if item.get("platforms"):
        _add(profile, "format", [f"платформа {platform}" for platform in item.get("platforms", [])])

    return {
        field: profile[field]
        for field in PROFILE_FIELDS
        if profile.get(field)
    }


def flatten_ai_profile(profile: dict | None) -> list[str]:
    if not isinstance(profile, dict):
        return []

    values: list[str] = []
    for field in PROFILE_FIELDS:
        raw_values = profile.get(field)
        if isinstance(raw_values, list):
            values.extend(str(value) for value in raw_values if value)
    return values
